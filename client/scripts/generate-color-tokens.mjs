// Generates src/sass/base/colors.generated.ts from src/sass/base/_colors.scss.
//
// SCSS variables cannot be read from TypeScript, and Turbopack does not support the
// ICSS `:export` trick, so the palette is transcribed into a TS module instead. That
// keeps _colors.scss the one place a colour is ever written down: the MUI theme and
// the inline SVGs read the generated copy, and this script regenerates it before
// every `yarn dev` and `yarn build`.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, "../src/sass/base/_colors.scss");
const TARGET = resolve(here, "../src/sass/base/colors.generated.ts");

const PREFIX = "$gy-v-";

/** `$gy-v-dark-green` -> `darkGreen`, `$gy-v-gray-400` -> `gray400`. */
const toCamelCase = (name) =>
  name
    .slice(PREFIX.length)
    .split("-")
    .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");

const scss = readFileSync(SOURCE, "utf8");

// Anchored to the start of a line so that `@function` bodies and `@return`s are never
// picked up, and greedy across newlines so that the Instagram gradient survives.
const declarations = [...scss.matchAll(/^(\$gy-v-[a-z0-9-]+):\s*([\s\S]*?);\s*(?:\/\/.*)?$/gm)];

const tokens = new Map();
for (const [, name, rawValue] of declarations) {
  const value = rawValue.split(/\s+/).join(" ").trim();
  // A token may alias another one, e.g. `$gy-v-tiktok: $gy-v-black;`.
  tokens.set(name, tokens.has(value) ? tokens.get(value) : value);
}

if (tokens.size === 0) {
  throw new Error(`No colour tokens found in ${SOURCE}`);
}

const body = [...tokens].map(([name, value]) => `  ${toCamelCase(name)}: "${value}",`).join("\n");

const output = `// AUTO-GENERATED by scripts/generate-color-tokens.mjs - do not edit.
// Add or change colours in sass/base/_colors.scss and the next \`yarn dev\` or
// \`yarn build\` will bring this file back in sync.

export const palette = {
${body}
} as const;

export type PaletteToken = keyof typeof palette;
`;

writeFileSync(TARGET, output);
console.log(`generate-color-tokens: wrote ${tokens.size} tokens to colors.generated.ts`);
